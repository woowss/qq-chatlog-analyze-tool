def emoji_for(name: str) -> str:
    """表情名 → emoji；没有对应时返回空串（调用方回退显示原名，不猜）"""
    key = (name or "").strip()
    if key.startswith("/"):
        key = key[1:]
    key = key.strip().strip("[]").strip()
    return FACE_EMOJI.get(key, "")


def emoji_map(names) -> dict:
    """{表情名: emoji}，只保留有对应的项（供前端渲染用）"""
    out = {}
    for name in names or []:
        char = emoji_for(name)
        if char:
            out[name] = char
    return out
