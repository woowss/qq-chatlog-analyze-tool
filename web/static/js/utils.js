// 共用前端工具：暴露唯一的 window.esc HTML 转义函数，避免各页面/脚本重复定义。

function esc(s) {
    return String(s == null ? '' : s)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}
window.esc = esc;
